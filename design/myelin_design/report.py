"""Render a lint report as Markdown. No dates or machine details, so the same code gives the same file."""

from __future__ import annotations

from typing import Any


_KIND_LABEL = {
    "literal": "hard-coded colour",
    "token-copy": "copy of a token",
    "unknown-token": "unknown token",
}


def _table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines


def _percent(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1f}%"


def _share(token_uses: int, hard_coded: int) -> str:
    """Compliance from the two counts, rounded once. Rounding a rounded figure can shift the last digit."""
    total = token_uses + hard_coded
    return "n/a" if total == 0 else f"{100 * token_uses / total:.1f}%"


def _context(result: dict[str, Any]) -> str:
    parts = [result["theme"]]
    if result["accent"]:
        parts.append(result["accent"])
    if result["sky"]:
        parts.append(f"{result['sky']} sky")
    return ", ".join(parts)


def _pair_name(result: dict[str, Any]) -> str:
    name = f"`--{result['foreground']}`"
    if result["opacity"] != 1:
        name += f" at {result['opacity']:g} opacity"
    return f"{name} on {result['surface']}"


def _threshold(result: dict[str, Any]) -> str:
    return "exempt" if result["threshold"] is None else f"{result['threshold']:g}:1"


def render(report: dict[str, Any]) -> str:
    c, k, f = report["compliance"], report["contrast"], report["focus"]
    out: list[str] = [
        "# Design lint report",
        "",
        "Generated by `python -m myelin_design lint --write`. Do not edit by hand.",
        "",
        f"**Result: {'pass' if report['ok'] else 'FAIL'}.** {report['files_scanned']} files scanned in `frontend/src`.",
        "",
    ]
    out += _table(
        ["Check", "Result"],
        [
            ["Token compliance", f"{_share(c['token_uses'], c['hard_coded'])} ({c['token_uses']} token uses, {c['hard_coded']} hard-coded colours, of which {c['allowed']} allowed)"],
            ["Contrast (WCAG 2.1 AA)", f"{k['measurements']} measurements of {k['declared_pairs']} declared pairs: {k['pass']} pass, {k['fail']} fail, {k['known']} known failures, {k['exempt']} exempt"],
            ["Focus states", f"{len(f['findings'])} findings; global `:focus-visible` rule {'found' if f['global_rule'] else 'MISSING'}"],
        ],
    )

    problems = {name: count for name, count in report["problems"].items() if count}
    if problems:
        out += ["", "To fix: " + ", ".join(f"{count} {name.replace('_', ' ')}" for name, count in problems.items()) + "."]

    # ---- Token compliance ----
    out += [
        "",
        "## Token compliance",
        "",
        "Compliance is token uses divided by all colour uses. A token use is `var(--name)` in CSS, or a token "
        "read at runtime in TypeScript. A hard-coded colour is a hex, `rgb()`, `hsl()` or named colour "
        "outside the token definitions. Allowed exceptions still count as hard-coded.",
        "",
    ]
    out += _table(
        ["File", "Token uses", "Hard-coded", "Compliance"],
        [[f"`{e['file']}`", e["token_uses"], e["hard_coded"], _share(e["token_uses"], e["hard_coded"])] for e in c["files"]]
        + [["**Total**", f"**{c['token_uses']}**", f"**{c['hard_coded']}**", f"**{_share(c['token_uses'], c['hard_coded'])}**"]],
    )
    if c["uncounted_rgb_triples"]:
        with_triples = 100 * c["token_uses"] / (c["token_uses"] + c["hard_coded"] + c["uncounted_rgb_triples"])
        out += [
            "",
            f"Not counted: {c['uncounted_rgb_triples']} bare `[r, g, b]` arrays in TypeScript that do not match a token. "
            "They are probably colours, but the scanner cannot tell a colour from any other three numbers. "
            f"Counting all of them as hard-coded colours would give {with_triples:.1f}%.",
        ]
    if c["findings"]:
        out += ["", "### Findings", ""]
        out += _table(
            ["Where", "Finding", "Text", "Note", "Status"],
            [
                [f"`{x['file']}:{x['line']}`", _KIND_LABEL[x["kind"]], f"`{x['text']}`", x["detail"], f"allowed: {x['allowed']}" if x["allowed"] else "**fix**"]
                for x in c["findings"]
            ],
        )
    for entry in c["stale_allow"]:
        out += ["", f"- Stale allowlist entry (matches nothing): `{entry}`"]
    for entry in c["tokens_outside_source"]:
        out += ["", f"- Custom property outside the token file: `{entry['file']}:{entry['line']}` `{entry['text']}`. The contract cannot see it."]

    # ---- Contrast ----
    out += [
        "",
        "## Contrast",
        "",
        "Each pair is a foreground token on a surface. Translucent layers are composited before measuring. "
        "Thresholds: 4.5:1 for text, 3:1 for non-text (control boundaries, states, the focus outline). "
        "Decorative and inactive pairs are measured but exempt. Ratios are cut to two decimals, never rounded up.",
    ]
    if k["sky"]:
        out += [
            "",
            "When Background is not Plain, the app paints a sky gradient behind the whole page: the sky colour at "
            "the top, 85% of the way to `--slide` two thirds down, and `--slide` at the bottom. So \"page\" results are "
            "exact only with the Plain background, or at the bottom of the screen. \"sky\" results use the colour at "
            "the very top. Over the gradient alone, a pair's real value lies between its page result and its sky "
            "result, depending on how high up it sits. Only pairs that occur in the header are measured on the sky. "
            "The clouds, mist, sun, moon, rain and cursor glow that are drawn over the gradient are not modelled, and "
            "they can lower contrast further, in both themes.",
        ]
    groups: dict[tuple, list[dict[str, Any]]] = {}
    for r in k["results"]:
        groups.setdefault((r["foreground"], r["surface"], r["kind"], r["opacity"], r["theme"]), []).append(r)
    rows = []
    for members in groups.values():
        worst = min(members, key=lambda r: r["ratio"])
        failed = [r for r in members if r["status"] in ("fail", "known")]
        if worst["threshold"] is None:
            verdict = "exempt"
        elif not failed:
            verdict = "pass"
        elif all(r["status"] == "known" for r in failed):
            verdict = f"known: {worst['known_failure']}"
        else:
            verdict = f"**{len(failed)} of {len(members)} fail**"
        at = ", ".join(part for part in (worst["accent"], f"{worst['sky']} sky" if worst["sky"] else None) if part) or "-"
        shown_as = f"`{worst['foreground_hex']}` on `{worst['background_hex']}`"
        rows.append((bool(failed), worst["ratio"], [_pair_name(worst), worst["kind"], worst["theme"], len(members), f"{worst['ratio']:.2f}", at, shown_as, _threshold(worst), verdict]))

    below = [row for failed, _, row in sorted((r for r in rows if r[0]), key=lambda r: r[1])]
    headers = ["Pair", "Kind", "Theme", "Measured", "Lowest", "Lowest at", "Shown as", "Needs", "Result"]
    if below:
        out += [
            "",
            "### Below the threshold",
            "",
            "One row per pair and theme. \"Measured\" counts the accents and skies the pair was measured under. "
            "Every single measurement is in `lint.json`.",
            "",
        ]
        out += _table(headers, below)

    out += ["", "### Every pair", "", "The lowest ratio for each pair in each theme, and where it occurs.", ""]
    out += _table(headers, [row for _, _, row in rows])

    out += ["", "### Where each pair occurs", ""]
    seen = set()
    for pair in k["pairs"]:
        key = (pair["foreground"], pair["kind"], pair["opacity"], pair["where"])
        if key in seen:
            continue
        seen.add(key)
        surfaces = ", ".join(p["surface"] for p in k["pairs"] if (p["foreground"], p["kind"], p["opacity"], p["where"]) == key)
        opacity = f" at {pair['opacity']:g} opacity" if pair["opacity"] != 1 else ""
        out.append(f"- `--{pair['foreground']}`{opacity} ({pair['kind']}) on {surfaces}: {pair['where']}")

    for entry in k["undeclared"]:
        on = f" on `--{entry['background']}`" if entry["background"] else ""
        out += ["", f"- Undeclared pair: `{entry['file']}:{entry['line']}` `{entry['selector']}` uses `--{entry['foreground']}`{on}. Add it to design.toml."]
    for entry in k["stale_known"]:
        out += ["", f"- {entry}"]

    # ---- Focus ----
    out += ["", "## Focus states", ""]
    if f["global_rule"]:
        g = f["global_rule"]
        out.append(f"Global rule: `:focus-visible {{ outline: {g['outline']} }}` at `{g['file']}:{g['line']}`.")
    if f["findings"]:
        out.append("")
        out += _table(
            ["Where", "Selector", "Text", "Problem"],
            [[f"`{x['file']}:{x['line']}`" if x["file"] else "-", f"`{x['selector']}`", f"`{x['text']}`" if x["text"] else "", x["message"]] for x in f["findings"]],
        )
    else:
        out += ["", "No rule or inline style removes the focus outline."]

    return "\n".join(out) + "\n"
